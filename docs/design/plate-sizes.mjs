/**
 * Measure every screenshot the project sheets draw, and write the map.
 *
 * The sheet lays plates out by shape: a row is one image or two, and the two
 * share a height while their widths divide the page in proportion to how wide
 * each picture actually is. That arithmetic needs the intrinsic size of each
 * file before React renders anything, which is also exactly what the `width`
 * and `height` attributes on `<img>` need to stop the page jumping as the
 * screenshots arrive.
 *
 * Reading it at runtime from `naturalWidth` would mean laying the page out
 * twice — once wrong, once right — in front of the visitor. So it is read
 * here, once, from the files themselves.
 *
 * Run after `shots.mjs` re-takes anything:
 *   node docs/design/plate-sizes.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "src/data/plateSizes.ts";

/**
 * WebP is three formats behind one wrapper, and the dimensions sit in a
 * different place in each. No dependency is worth the 12 lines.
 */
function dimensions(file) {
  const b = readFileSync("public" + file);
  if (b.slice(0, 4).toString() !== "RIFF" || b.slice(8, 12).toString() !== "WEBP")
    throw new Error(`${file} is not a WebP`);

  const chunk = b.slice(12, 16).toString();
  if (chunk === "VP8X") return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
  if (chunk === "VP8 ")
    return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  if (chunk === "VP8L") {
    const bits = b.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1];
  }
  throw new Error(`${file} has an unknown WebP chunk: ${chunk}`);
}

const projects = JSON.parse(readFileSync("src/data/Projects.json", "utf8"));

/* Only what a sheet draws as a plate. Covers are cropped to a fixed box by the
   index and never need their own shape. */
const files = [
  ...new Set(
    projects.flatMap((p) => [
      p.image2,
      ...Object.values(p.plates ?? {}).flat(),
    ]),
  ),
].filter(Boolean).sort();

const rows = files.map((file) => {
  const [w, h] = dimensions(file);
  return `  ${JSON.stringify(file)}: [${w}, ${h}],`;
});

writeFileSync(
  OUT,
  `/**
 * Intrinsic size of every screenshot the project sheets draw, in pixels.
 *
 * Generated by docs/design/plate-sizes.mjs — do not edit by hand. Re-run it
 * whenever shots.mjs re-takes a screenshot:
 *
 *   node docs/design/plate-sizes.mjs
 */
export const PLATE_SIZES: Record<string, [number, number]> = {
${rows.join("\n")}
};

/** How wide the picture is relative to its height. */
export function plateRatio(src: string): number {
  const size = PLATE_SIZES[src];
  // A missing entry means the map is stale, not that the page should break:
  // 16/10 is the shape the shots harness takes covers at.
  return size ? size[0] / size[1] : 1.6;
}
`,
);

console.log(`wrote ${OUT} — ${files.length} plates`);
